#!/usr/bin/env node
/**
 * Writes host-level 301s that send every Netlify alias domain to its site's
 * primary domain, so an alias never serves a duplicate copy of a site.
 *
 * Source: entity/domains.json ({ primary: { repo, redirectsFile, aliases[], skip[] } }).
 * Refresh it from Netlify first when aliases change:
 *
 *   node scripts/build-alias-redirects.mjs --refresh   # re-read aliases via the Netlify CLI
 *   node scripts/build-alias-redirects.mjs             # write the blocks
 *   node scripts/build-alias-redirects.mjs --check     # fail if any block is stale
 *
 * Each site's redirects file gets one generated block between markers, placed
 * at the top so alias rules win before any path rule can match on an alias host.
 * `skip` lists aliases that already have their own hand-written rule.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ENTITY = join(HERE, '..', 'entity');
const DEV = resolve(HERE, '..', '..', '..', '..', '..');
const DOMAINS = join(ENTITY, 'domains.json');
const START = '# alias-redirects:start (generated by alexmercedcom/scripts/build-alias-redirects.mjs; do not edit)';
const END = '# alias-redirects:end';
const args = process.argv.slice(2);

const domains = JSON.parse(readFileSync(DOMAINS, 'utf8'));

if (args.includes('--refresh')) {
  const pages = [1, 2, 3].flatMap((page) =>
    JSON.parse(execSync(`netlify api listSites --data '{"per_page":100,"page":${page},"filter":"all"}'`, { encoding: 'utf8' }))
  );
  for (const [primary, cfg] of Object.entries(domains.sites)) {
    const site = pages.find((s) => s.custom_domain === primary || (s.domain_aliases || []).includes(primary));
    if (!site) throw new Error(`No Netlify site serves ${primary}`);
    cfg.aliases = [site.custom_domain, ...(site.domain_aliases || [])]
      .filter((d) => d && d !== primary && d !== `www.${primary}`)
      .sort();
  }
  domains.refreshed = new Date().toISOString().slice(0, 10);
  writeFileSync(DOMAINS, JSON.stringify(domains, null, 2) + '\n');
  console.log(`Refreshed aliases for ${Object.keys(domains.sites).length} sites.`);
}

let stale = 0;
for (const [primary, cfg] of Object.entries(domains.sites)) {
  const file = join(DEV, cfg.repo, cfg.redirectsFile);
  const aliases = cfg.aliases.filter((a) => !(cfg.skip || []).includes(a));
  const block = [
    START,
    `# ${aliases.length} alias domain(s) of ${primary}; refreshed ${domains.refreshed}`,
    ...aliases.map((a) => `https://${a}/*  https://${primary}/:splat  301!`),
    END,
  ].join('\n');
  const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
  const rest = current.includes(START) ? current.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}\\n?`), '') : current;
  const next = `${block}\n${rest.replace(/^\n+/, '')}`;
  if (next === current) continue;
  if (args.includes('--check')) {
    console.error(`stale: ${cfg.repo}/${cfg.redirectsFile}`);
    stale++;
    continue;
  }
  writeFileSync(file, next);
  console.log(`${primary}: ${aliases.length} alias rule(s) -> ${cfg.repo}/${cfg.redirectsFile}`);
}
if (stale) process.exit(1);
